"""Unified benchmark runner for Phase 7.

Usage:
    python -m experiments.run_all --config experiments/config.yaml --quick
    python -m experiments.run_all --config experiments/config.yaml
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path
from typing import Any

import yaml

from experiments.base import Experiment
from experiments.env_info import write_environment_json
from experiments.studies import (
    StudyS1HLLStats,
    StudyS2ParamGrid,
    StudyS3CMSAblation,
    StudyS4HashAblation,
    StudyS5Scalability,
    StudyS6SparseHLL,
    StudyS7SlidingWindow,
    StudyS8Adversarial,
)


def _rows_to_markdown_table(rows: list[dict[str, Any]]) -> str:
    if not rows:
        return "_No data._\n"
    cols = list(rows[0].keys())
    header = "| " + " | ".join(cols) + " |"
    sep = "| " + " | ".join(["---"] * len(cols)) + " |"
    body = ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join([header, sep, *body]) + "\n"


def _generate_results_md(
    out_path: Path,
    env: dict[str, Any],
    studies: list[Experiment],
) -> None:
    lines = [
        "# Benchmark Results Summary",
        "",
        "Auto-generated by `python -m experiments.run_all`.",
        "",
        "## Environment",
        "",
        f"- **Python**: `{env['python_version']}`",
        f"- **Platform**: `{env['platform']}`",
        f"- **CPU cores**: `{env['cpu_count']}` | **RAM**: `{env['ram_gb']} GB`",
        f"- **Git commit**: `{env['git_commit']}`",
        "",
    ]

    for study in studies:
        lines.append(f"## {study.name}")
        lines.append("")
        lines.append(f"![{study.name}](figures/{study.figure_stem}.png)")
        lines.append("")
        lines.append(f"*{study.caption}*")
        lines.append("")
        lines.append(_rows_to_markdown_table(study.rows))

    # Also reference earlier phase figures so docs/results.md links all 14+ figures
    extra_figs = [
        (
            "Phase 2 — E1: Error vs Cardinality",
            "e1_error_vs_cardinality.png",
            "Mean error stays near 0.81% across cardinalities.",
        ),
        (
            "Phase 2 — E3: HLL Memory vs Exact Set",
            "e3_memory.png",
            "HLL uses a fixed 12 KB while exact sets grow linearly.",
        ),
        (
            "Phase 3 — C1: CMS Error vs Width",
            "c1_error_vs_width.png",
            "Observed CMS error stays well below the theoretical (e/w)*N bound.",
        ),
        (
            "Phase 3 — C4: Heavy Hitters vs Long Tail",
            "c4_heavy_vs_tail.png",
            "CMS achieves <1% error on heavy hitters while long-tail relative error is higher.",
        ),
        (
            "Phase 4 — A1: 7-Day Hourly Series",
            "a1_hourly_series.png",
            "Hourly HyperLogLog series closely tracks exact unique visitors.",
        ),
        (
            "Phase 4 — A3: Inclusion-Exclusion Intersection",
            "a3_intersection.png",
            "Intersection relative error spikes below 5% overlap, triggering the warning.",
        ),
    ]
    lines.append("## Additional Phase 2–4 Figures")
    lines.append("")
    for title, fname, cap in extra_figs:
        if (Path("docs/figures") / fname).exists():
            lines.append(f"### {title}")
            lines.append(f"![{title}](figures/{fname})")
            lines.append(f"*{cap}*")
            lines.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Run unified Phase 7 benchmark suite.")
    parser.add_argument("--config", default="experiments/config.yaml")
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args(argv)

    with open(args.config, encoding="utf-8") as f:
        cfg = yaml.safe_load(f)

    results_dir = Path(cfg.get("results_dir", "experiments/results"))
    env = write_environment_json(results_dir / "environment.json")

    study_classes: list[type[Experiment]] = [
        StudyS1HLLStats,
        StudyS2ParamGrid,
        StudyS3CMSAblation,
        StudyS4HashAblation,
        StudyS5Scalability,
        StudyS6SparseHLL,
        StudyS7SlidingWindow,
        StudyS8Adversarial,
    ]

    completed: list[Experiment] = []
    t_total = time.perf_counter()
    for cls in study_classes:
        t0 = time.perf_counter()
        exp = cls(cfg, quick=args.quick)
        exp.setup()
        exp.run()
        exp.save()
        exp.plot()
        completed.append(exp)
        print(f"Completed {exp.name} in {time.perf_counter() - t0:.2f}s", flush=True)

    _generate_results_md(Path(cfg.get("docs_results", "docs/results.md")), env, completed)
    print(f"Benchmark suite finished in {time.perf_counter() - t_total:.2f}s")


if __name__ == "__main__":
    main()
